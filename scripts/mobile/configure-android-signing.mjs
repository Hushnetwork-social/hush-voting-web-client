import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';

const buildFile = path.resolve('src-tauri/gen/android/app/build.gradle.kts');
const marker = '// HushVoting release signing (generated by scripts/mobile/configure-android-signing.mjs)';
let source = await readFile(buildFile, 'utf8');

if (source.includes(marker)) {
  console.log('Android release signing is already configured.');
  process.exit(0);
}

const androidBlock = 'android {\n';
const releaseBlock = '        getByName("release") {\n';

if (!source.includes(androidBlock) || !source.includes(releaseBlock)) {
  throw new Error(`Generated Android Gradle structure was not recognized: ${buildFile}`);
}

const signingConfiguration = `android {\n    ${marker}\n    signingConfigs {\n        create("release") {\n            val keystorePath = System.getenv("ANDROID_KEYSTORE_PATH")\n                ?: error("ANDROID_KEYSTORE_PATH is required for release signing")\n            storeFile = file(keystorePath)\n            storePassword = System.getenv("ANDROID_KEYSTORE_PASSWORD")\n                ?: error("ANDROID_KEYSTORE_PASSWORD is required for release signing")\n            keyAlias = System.getenv("ANDROID_KEY_ALIAS")\n                ?: error("ANDROID_KEY_ALIAS is required for release signing")\n            keyPassword = System.getenv("ANDROID_KEY_PASSWORD")\n                ?: error("ANDROID_KEY_PASSWORD is required for release signing")\n        }\n    }\n`;

source = source.replace(androidBlock, signingConfiguration);
source = source.replace(
  releaseBlock,
  `${releaseBlock}            signingConfig = signingConfigs.getByName("release")\n`,
);

await writeFile(buildFile, source, 'utf8');
console.log(`Configured Android release signing in ${buildFile}`);
